"""Trivia: questions for class quizzes and trivia games.

Subjects come from data/trivia.json (written questions, each with the grade it fits) plus dialogue packs' 'trivia' section.
Math is generated by course (Algebra I, Geometry, Algebra II, Pre-Calculus, Calculus, Statistics), so it never runs out
and every answer is computed, not typed.
"""
from __future__ import annotations

import json
import math
import os
import random

from .catalogs import DATA_DIR

_BANK = None
SUP = str.maketrans("0123456789-", "⁰¹²³⁴⁵⁶⁷⁸⁹⁻")


def sup(n) -> str:
    return str(n).translate(SUP)


def bank() -> dict:
    global _BANK
    if _BANK is None:
        with open(os.path.join(DATA_DIR, "trivia.json"), encoding="utf-8") as f:
            _BANK = json.load(f)
    return _BANK


def questions(subject: str) -> list:
    from . import dialogue
    base = list(bank()["questions"].get(subject, []))
    extra = dialogue.merged().get("trivia", {}).get(subject, [])
    return base + extra


def subjects() -> dict:
    return bank()["subjects"]


# ------------------------------------------------------------------------------------------- math

def _choices(rng, right, wrong) -> tuple[list, int]:
    """Right answer plus three different wrong ones, shuffled."""
    seen = {str(right)}
    w = []
    for x in wrong:
        if str(x) not in seen:
            seen.add(str(x))
            w.append(str(x))
        if len(w) == 3:
            break
    k = 1
    while len(w) < 3:  # top up with nearby numbers if the generator's distractors collided
        try:
            cand = str(int(str(right)) + k * (1 if k % 2 else -1))
        except ValueError:
            cand = f"{right} ({k})"
        if cand not in seen:
            seen.add(cand)
            w.append(cand)
        k += 1
    opts = [str(right)] + w
    rng.shuffle(opts)
    return opts, opts.index(str(right))


def _lin(rng):
    a = rng.choice([2, 3, 4, 5, 6, 7, 8, 9])
    x = rng.randint(-6, 12)
    b = rng.choice([v for v in range(-15, 16) if v != 0])
    c = a * x + b
    sign = "+" if b > 0 else "−"
    q = f"Solve for x: {a}x {sign} {abs(b)} = {c}"
    return q, x, [x + 1, x - 1, -x if x else 2, (c + b) // a if (c + b) % a == 0 else x + 2]


def _slope(rng):
    m = rng.choice([-4, -3, -2, -1, 1, 2, 3, 4, 5])
    x1 = rng.randint(-5, 5)
    x2 = x1 + rng.choice([1, 2, 3, 4])
    y1 = rng.randint(-6, 6)
    y2 = y1 + m * (x2 - x1)
    return f"What is the slope of the line through ({x1}, {y1}) and ({x2}, {y2})?", m, [-m, m + 1, m - 1, x2 - x1]


def _evaluate(rng):
    a, b, c = rng.choice([1, 2, 3]), rng.choice([-5, -4, -3, -2, 2, 3, 4]), rng.randint(-6, 6)
    k = rng.choice([-3, -2, -1, 2, 3, 4])
    val = a * k * k + b * k + c
    bs = f"+ {b}x" if b > 0 else f"− {abs(b)}x"
    cs = f"+ {c}" if c > 0 else (f"− {abs(c)}" if c < 0 else "")
    lead = "x²" if a == 1 else f"{a}x²"
    q = f"If f(x) = {lead} {bs} {cs}".rstrip() + f", what is f({k})?"
    return q, val, [val + 2 * b * k, -val, a * k + b * k + c, val + 1]


def _triangle(rng):
    a = rng.randint(25, 85)
    b = rng.randint(20, 150 - a)
    return f"Two angles of a triangle are {a}° and {b}°. What is the third angle?", f"{180 - a - b}°", [f"{180 - a}°", f"{360 - a - b}°", f"{abs(a - b)}°", f"{90 - (a + b) // 4}°"]


def _pythag(rng):
    a, b, c = rng.choice([(3, 4, 5), (5, 12, 13), (8, 15, 17), (7, 24, 25), (6, 8, 10), (9, 12, 15)])
    k = rng.choice([1, 1, 2])
    a, b, c = a * k, b * k, c * k
    return f"A right triangle has legs {a} and {b}. How long is the hypotenuse?", c, [a + b, c + 1, c - 1, b + 1]


def _circle(rng):
    r = rng.randint(2, 9)
    return f"What is the area of a circle with radius {r}?", f"{r * r}π", [f"{2 * r}π", f"{r}π", f"{r * r * 2}π", f"{(r + 1) * (r + 1)}π"]


def _polygon(rng):
    n, name = rng.choice([(5, "pentagon"), (6, "hexagon"), (8, "octagon"), (10, "decagon")])
    s = (n - 2) * 180
    return f"What is the sum of the interior angles of a {name}?", f"{s}°", [f"{n * 180}°", f"{s - 180}°", f"{s + 180}°", "360°"]


def _exponent(rng):
    a, b = rng.randint(2, 7), rng.randint(2, 7)
    return f"Simplify: x{sup(a)} · x{sup(b)}", f"x{sup(a + b)}", [f"x{sup(a * b)}", f"x{sup(abs(a - b) or 1)}", f"2x{sup(a + b)}", f"x{sup(a + b + 1)}"]


def _quadratic(rng):
    p, q = rng.sample([-6, -5, -4, -3, -2, -1, 1, 2, 3, 4, 5, 6, 7], 2)
    p, q = min(p, q), max(p, q)
    s, pr = p + q, p * q
    bs = (f"− {s}x" if s > 0 else f"+ {-s}x") if s != 0 else ""
    cs = f"+ {pr}" if pr > 0 else f"− {abs(pr)}"
    eq = " ".join(x for x in ("x²", bs, cs) if x) + " = 0"
    fmt = lambda u, v: f"x = {min(u, v)} or x = {max(u, v)}"  # noqa: E731
    return f"Solve: {eq}", fmt(p, q), [fmt(-p, -q), fmt(p, -q), fmt(s, pr) if s != pr else fmt(p + 1, q + 1), fmt(p - 1, q + 1)]


def _linear_fn(rng):
    a, b, k = rng.choice([2, 3, 4, 5, -2, -3]), rng.randint(-9, 9), rng.randint(-4, 6)
    bs = f"+ {b}" if b > 0 else (f"− {abs(b)}" if b < 0 else "")
    return f"If g(x) = {a}x {bs}".rstrip() + f", what is g({k})?", a * k + b, [a + k + b, a * (k + b), -(a * k + b) if a * k + b else 1, a * k - b]


TRIG = [("sin 30°", "1/2"), ("cos 60°", "1/2"), ("sin 90°", "1"), ("cos 0°", "1"), ("tan 45°", "1"), ("sin 45°", "√2/2"),
        ("cos 45°", "√2/2"), ("cos 30°", "√3/2"), ("sin 60°", "√3/2"), ("sin 0°", "0"), ("cos 90°", "0")]


def _trig(rng):
    expr, val = rng.choice(TRIG)
    wrong = [v for v in ["0", "1/2", "√2/2", "√3/2", "1", "2"] if v != val]
    rng.shuffle(wrong)
    return f"What is {expr}?", val, wrong


def _log(rng):
    base = rng.choice([2, 3, 10])
    k = rng.randint(2, 5 if base != 10 else 4)
    return f"What is log{''.join('₀₁₂₃₄₅₆₇₈₉'[int(d)] for d in str(base))}({base ** k})?", k, [k + 1, k - 1, base * k, base ** (k - 1)]


def _derivative(rng):
    a, n = rng.randint(2, 9), rng.randint(2, 6)
    ex = lambda p: "" if p == 1 else sup(p)  # noqa: E731
    right = f"{a * n}x{ex(n - 1)}"
    return f"What is the derivative of {a}x{sup(n)}?", right, [f"{a * n}x{sup(n)}", f"{a}x{ex(n - 1)}", f"{a + n}x{ex(n - 1)}", f"{n}x{ex(n - 1)}"]


def _deriv_at(rng):
    b, k = rng.randint(1, 9), rng.randint(-3, 5)
    val = 2 * k + b
    bx = "x" if b == 1 else f"{b}x"
    return f"If f(x) = x² + {bx}, what is f′({k})?", val, [k * k + b * k, 2 * k, val + 1, b]


def _mean(rng):
    xs = [rng.randint(60, 99) for _ in range(4)]
    target = rng.randint(70, 95)
    xs.append(target * 5 - sum(xs))
    if not 40 <= xs[-1] <= 100:
        xs[-1] = 80
        target = None
    nums = ", ".join(str(x) for x in xs)
    mean = sum(xs) / 5
    right = int(mean) if float(mean).is_integer() else round(mean, 1)
    med = sorted(xs)[2]
    return f"What is the mean of {nums}?", right, [med if med != right else med + 1, max(xs), right + 2, right - 3]


def _median(rng):
    xs = rng.sample(range(2, 40), 5)
    med = sorted(xs)[2]
    mean = round(sum(xs) / 5, 1)
    return f"What is the median of {', '.join(str(x) for x in xs)}?", med, [int(mean) if mean != med else med + 2, xs[2] if xs[2] != med else med - 1, max(xs), min(xs)]


COURSES = {
    "algebra1": [_lin, _slope, _evaluate, _linear_fn],
    "geometry": [_triangle, _pythag, _circle, _polygon],
    "algebra2": [_exponent, _quadratic, _linear_fn, _evaluate],
    "precalc": [_trig, _log, _quadratic, _exponent],
    "calculus": [_derivative, _deriv_at, _trig, _log],
    "statistics": [_mean, _median, _slope, _evaluate],
}


def math_question(rng, course="algebra1") -> dict:
    q, right, wrong = rng.choice(COURSES.get(course) or COURSES["algebra1"])(rng)
    opts, idx = _choices(rng, right, wrong)
    return {"q": q, "choices": opts, "answer": idx, "subject": "math"}


# ------------------------------------------------------------------------------------------- rounds

def _pick(rng, subject, grade, seen) -> dict | None:
    pool = [q for q in questions(subject) if q.get("g", 9) <= max(grade, 9) + 1]
    if not pool:
        pool = questions(subject)
    if not pool:
        return None
    fresh = [q for q in pool if q["q"] not in seen] or pool
    q = rng.choice(fresh)
    seen.add(q["q"])
    opts = [q["a"]] + list(q["w"])[:3]
    rng.shuffle(opts)
    return {"q": q["q"], "choices": opts, "answer": opts.index(q["a"]), "subject": subject}


def round_for(sim, c, ctx: dict, seed: int) -> list:
    """The questions for one round: a class quiz (that class's subject), a test (all your classes), or general trivia."""
    rng = random.Random(seed)
    n = int(ctx.get("n") or 5)
    subs = ctx.get("subjects") or ["general"]
    courses = ctx.get("math_courses") or ["algebra1"]
    grade = c.grade or 9
    seen_list = sim.w.meta.setdefault("trivia_seen", [])
    seen = set(seen_list)
    out = []
    for i in range(n):
        s = subs[i % len(subs)]
        q = math_question(rng, courses[i % len(courses)]) if s == "math" else _pick(rng, s, grade, seen)
        if q is None:
            q = math_question(rng, courses[0])
        out.append(q)
    seen_list.extend(q["q"] for q in out if q["subject"] != "math")
    del seen_list[:-400]
    return out
